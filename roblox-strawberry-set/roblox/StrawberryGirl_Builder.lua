--[[
	Strawberry Beanie Girl - Roblox Studio rig builder

	Builds an R15 girl rig and dresses it with the Blender-made set:
	  SB_Head            -> custom chibi head + painted face (Face accessory, default head hidden)
	  SB_Hair            -> long wavy blonde hair (Hair accessory)
	  SB_Beanie          -> pink strawberry beanie (Hat accessory)
	  SB_HairBeanieCombo -> hair + beanie in one accessory (used when CONFIG.UseCombo = true)

	How to use:
	  1. Studio > Avatar (or Home) > Import 3D: import exports/SB_Head.fbx, SB_Hair.fbx,
	     SB_Beanie.fbx (and optionally SB_HairBeanieCombo.fbx) into Workspace.
	     The importer keeps the embedded textures; if one is missing, upload the PNG from
	     textures/ and put its id in CONFIG below.
	  2. (optional) Upload textures/SB_Shirt_Template.png and SB_Pants_Template.png as
	     Shirt / Pants (or as Decals) and put the image ids in CONFIG.
	  3. Paste this whole file into View > Command Bar and press Enter
	     (or run it through the Roblox Studio MCP "run_code" tool).

	The script finds the imported MeshParts by name anywhere in Workspace / ServerStorage /
	ReplicatedStorage, so they can stay where the importer put them.
]]

local CONFIG = {
	RigName = "StrawberryGirl",
	Position = Vector3.new(0, 5.2, 0), -- HumanoidRootPart position
	UseCombo = false, -- true: one SB_HairBeanieCombo accessory instead of SB_Hair + SB_Beanie
	UseCustomHead = true, -- false: keep the default R15 head and use FaceDecalId
	Rotate180 = false, -- set true only if the imported meshes face backwards

	-- optional asset ids (numbers). 0 = not used / keep what the importer set.
	ShirtTemplateId = 0,
	PantsTemplateId = 0,
	FaceDecalId = 0,
	HairBeanieTextureId = 0,
	HeadTextureId = 0,
}

-- Mesh bounds measured in Blender, in studs, relative to the head centre (Roblox axes).
-- Regenerated by blender/build_strawberry_set.py - do not edit by hand.
-- BEGIN GENERATED MESH DATA
local MESH_DATA = {
	SB_Head = { center = Vector3.new(-0.0, 0.0, 0.0), size = Vector3.new(1.24, 1.24, 1.16), tris = 3472 },
	SB_Hair = { center = Vector3.new(0.0128, -1.0388, -0.0066), size = Vector3.new(2.5595, 3.3876, 1.695), tris = 3826 },
	SB_Beanie = { center = Vector3.new(-0.0, 0.4427, 0.1146), size = Vector3.new(1.5744, 1.0989, 1.6262), tris = 2364 },
	SB_HairBeanieCombo = { center = Vector3.new(0.0509, -0.8707, 0.0453), size = Vector3.new(2.4894, 3.7257, 1.7647), tris = 3787 },
}
-- END GENERATED MESH DATA

local SKIN = Color3.fromRGB(245, 215, 195)
local DEFAULT_HEAD_ATTACHMENTS = {
	HatAttachment = Vector3.new(0, 0.6, 0),
	HairAttachment = Vector3.new(0, 0.6, 0),
	FaceCenterAttachment = Vector3.new(0, 0, 0),
}

local Players = game:GetService("Players")
local ServerStorage = game:GetService("ServerStorage")
local ReplicatedStorage = game:GetService("ReplicatedStorage")

local function assetUrl(id)
	return "rbxassetid://" .. tostring(id)
end

local function findMesh(name)
	local fuzzy
	for _, root in ipairs({ workspace, ServerStorage, ReplicatedStorage }) do
		for _, inst in ipairs(root:GetDescendants()) do
			if inst:IsA("MeshPart") and not inst:FindFirstAncestorOfClass("Accessory") then
				if inst.Name == name then
					return inst
				end
				-- the importer sometimes names the part after the file/model instead
				local parentName = inst.Parent and inst.Parent.Name or ""
				if not fuzzy and (string.find(inst.Name, name, 1, true) or parentName == name) then
					fuzzy = inst
				end
			end
		end
	end
	return fuzzy
end

local function buildRig()
	local old = workspace:FindFirstChild(CONFIG.RigName)
	if old then
		old:Destroy()
	end

	local desc = Instance.new("HumanoidDescription")
	desc.HeadColor = SKIN
	desc.TorsoColor = SKIN
	desc.LeftArmColor = SKIN
	desc.RightArmColor = SKIN
	desc.LeftLegColor = SKIN
	desc.RightLegColor = SKIN
	desc.DepthScale = 0.95
	desc.WidthScale = 0.95
	desc.HeadScale = 1

	local ok, rig = pcall(function()
		return Players:CreateHumanoidModelFromDescription(desc, Enum.HumanoidRigType.R15)
	end)
	if not ok or not rig then
		-- fallback: a rig made with Avatar > Rig Builder (R15 Block) named "Rig"
		local existing = workspace:FindFirstChild("Rig")
		if existing and existing:FindFirstChildOfClass("Humanoid") then
			rig = existing
			local colors = rig:FindFirstChildOfClass("BodyColors") or Instance.new("BodyColors", rig)
			for _, prop in ipairs({ "HeadColor3", "TorsoColor3", "LeftArmColor3", "RightArmColor3", "LeftLegColor3", "RightLegColor3" }) do
				colors[prop] = SKIN
			end
		else
			error("Could not create the rig (" .. tostring(rig) .. "). Use Avatar > Rig Builder > R15 Block, keep it named 'Rig' and run again.")
		end
	end

	rig.Name = CONFIG.RigName
	rig.Parent = workspace
	local root = rig:WaitForChild("HumanoidRootPart")
	root.Anchored = true
	rig:PivotTo(CFrame.new(CONFIG.Position))
	return rig
end

local function dressClothing(rig)
	for _, c in ipairs(rig:GetChildren()) do
		if c:IsA("Shirt") or c:IsA("Pants") or c:IsA("ShirtGraphic") then
			c:Destroy()
		end
	end
	if CONFIG.ShirtTemplateId ~= 0 then
		local shirt = Instance.new("Shirt")
		shirt.ShirtTemplate = assetUrl(CONFIG.ShirtTemplateId)
		shirt.Parent = rig
	end
	if CONFIG.PantsTemplateId ~= 0 then
		local pants = Instance.new("Pants")
		pants.PantsTemplate = assetUrl(CONFIG.PantsTemplateId)
		pants.Parent = rig
	end
end

local function makeAccessory(rig, meshName, accName, accType, attName, textureId)
	local src = findMesh(meshName)
	local data = MESH_DATA[meshName]
	if not src then
		warn(("[StrawberryGirl] MeshPart '%s' not found - import exports/%s.fbx first."):format(meshName, meshName))
		return nil
	end
	if not data then
		warn(("[StrawberryGirl] No mesh data for '%s' - re-run the Blender script."):format(meshName))
		return nil
	end

	local handle = src:Clone()
	for _, c in ipairs(handle:GetChildren()) do
		if c:IsA("Attachment") or c:IsA("JointInstance") or c:IsA("WeldConstraint") then
			c:Destroy()
		end
	end
	handle.Name = "Handle"
	handle.Anchored = false
	handle.CanCollide = false
	handle.CanTouch = false
	handle.CanQuery = false
	handle.Massless = true
	handle.CastShadow = true

	-- normalise the size (guards against unit-scale differences on import)
	local s, e = handle.Size, data.size
	local rx, ry, rz = s.X / e.X, s.Y / e.Y, s.Z / e.Z
	if math.max(rx, ry, rz) / math.min(rx, ry, rz) > 1.15 then
		warn(("[StrawberryGirl] %s proportions differ from Blender (%s vs %s) - check the importer's axis settings.")
			:format(meshName, tostring(s), tostring(e)))
	end
	handle.Size = e
	if textureId and textureId ~= 0 then
		handle.TextureID = assetUrl(textureId)
	end

	local acc = Instance.new("Accessory")
	acc.Name = accName
	acc.AccessoryType = accType
	handle.Parent = acc

	local head = rig:FindFirstChild("Head")
	local headAtt = head:FindFirstChild(attName)
	if not headAtt then
		headAtt = Instance.new("Attachment")
		headAtt.Name = attName
		headAtt.Position = DEFAULT_HEAD_ATTACHMENTS[attName]
		headAtt.Parent = head
	end

	-- where the mesh must sit relative to the head, then solve the handle attachment:
	-- handle.CFrame * att.CFrame == head.CFrame * headAtt.CFrame
	local rel = CFrame.new(data.center)
	if CONFIG.Rotate180 then
		rel = rel * CFrame.Angles(0, math.pi, 0)
	end
	local att = Instance.new("Attachment")
	att.Name = attName
	att.CFrame = rel:Inverse() * headAtt.CFrame
	att.Parent = handle

	acc.Parent = rig
	handle.CFrame = head.CFrame * rel
	local humanoid = rig:FindFirstChildOfClass("Humanoid")
	local ok = pcall(function()
		humanoid:AddAccessory(acc)
	end)
	if not ok or not handle:FindFirstChild("AccessoryWeld") then
		local weld = Instance.new("Weld")
		weld.Name = "AccessoryWeld"
		weld.Part0 = handle
		weld.Part1 = head
		weld.C0 = att.CFrame
		weld.C1 = headAtt.CFrame
		weld.Parent = handle
	end
	return acc
end

local function build()
	local rig = buildRig()
	dressClothing(rig)
	local head = rig:FindFirstChild("Head")

	if CONFIG.UseCustomHead then
		local acc = makeAccessory(rig, "SB_Head", "SB_Head", Enum.AccessoryType.Face, "FaceCenterAttachment", CONFIG.HeadTextureId)
		if acc then
			head.Transparency = 1
			local face = head:FindFirstChild("face")
			if face then
				face:Destroy()
			end
		end
	elseif CONFIG.FaceDecalId ~= 0 then
		local face = head:FindFirstChild("face") or Instance.new("Decal")
		face.Name = "face"
		face.Face = Enum.NormalId.Front
		face.Texture = assetUrl(CONFIG.FaceDecalId)
		face.Parent = head
	end

	if CONFIG.UseCombo then
		makeAccessory(rig, "SB_HairBeanieCombo", "SB_HairBeanieCombo", Enum.AccessoryType.Hat, "HatAttachment", CONFIG.HairBeanieTextureId)
	else
		makeAccessory(rig, "SB_Hair", "SB_Hair", Enum.AccessoryType.Hair, "HairAttachment", CONFIG.HairBeanieTextureId)
		makeAccessory(rig, "SB_Beanie", "SB_Beanie", Enum.AccessoryType.Hat, "HatAttachment", CONFIG.HairBeanieTextureId)
	end

	pcall(function()
		game:GetService("Selection"):Set({ rig })
	end)
	print(("[StrawberryGirl] '%s' built at %s"):format(rig.Name, tostring(CONFIG.Position)))
	return rig
end

build()
